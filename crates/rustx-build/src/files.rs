//! Desugaring `.rustx` files into `OUT_DIR` from a build script, for `include!`.

use std::fmt;
use std::fs;
use std::path::{Component, Path, PathBuf};

use crate::{Kind, expand_source, render};

/// Why a file could not be desugared: one `path:line:column: message` line per problem, or
/// `path: reason` when the file itself could not be read or written.
pub struct Error {
    message: String,
}

impl Error {
    fn new(message: String) -> Self {
        Self { message }
    }

    /// Reports the error to Cargo as `cargo::error` lines. Cargo then fails the build and prints
    /// each line as an `error:` of its own, without the build script's other output.
    pub fn emit(&self) {
        for line in self.cargo_lines() {
            println!("{line}");
        }
    }

    // One directive per line: a message line printed as is would be read as a directive of its
    // own, so source text quoted in a message could otherwise inject one.
    fn cargo_lines(&self) -> impl Iterator<Item = String> + '_ {
        self.message
            .lines()
            .map(|line| format!("cargo::error={line}"))
    }
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.message)
    }
}

// `fn main() -> Result<(), Error>` and `unwrap` print the `Debug` form; the rendered lines are
// what the reader needs there, not a struct dump with escaped line breaks.
impl fmt::Debug for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.message)
    }
}

impl std::error::Error for Error {}

/// Desugars the file at `path` into `$OUT_DIR` and returns the path of the output.
///
/// `path` is relative to the package root, the build script's working directory. The output keeps
/// that relative path with the extension `rs`: `src/lib.rustx` becomes `$OUT_DIR/src/lib.rs`, so
/// two sources never share an output. A `.rustx` file is sugar throughout; in any other file only
/// `sugar! { .. }` invocations are expanded. Prints `cargo::rerun-if-changed=<path>`.
///
/// # Errors
///
/// Returns every desugaring error of the file, or why it could not be read or written; see
/// [`Error`].
pub fn expand_file(path: impl AsRef<Path>) -> Result<PathBuf, Error> {
    expand_into(path.as_ref(), &out_dir()?)
}

/// Desugars every `.rustx` file below `dir` as [`expand_file`] does, and returns the outputs.
///
/// Also prints `cargo::rerun-if-changed=<dir>`, so an added or removed file reruns the build
/// script too.
///
/// # Errors
///
/// Returns the errors of every file that failed, after expanding all the others.
pub fn expand_dir(dir: impl AsRef<Path>) -> Result<Vec<PathBuf>, Error> {
    expand_dir_into(dir.as_ref(), &out_dir()?)
}

fn out_dir() -> Result<PathBuf, Error> {
    std::env::var_os("OUT_DIR")
        .map(PathBuf::from)
        .ok_or_else(|| Error::new("OUT_DIR is not set; call rustx-build from build.rs".into()))
}

fn expand_into(path: &Path, out_dir: &Path) -> Result<PathBuf, Error> {
    rerun_if_changed(path)?;
    let output = out_dir.join(path).with_extension("rs");
    let source = fs::read_to_string(path).map_err(|err| io_error(path, &err))?;
    let expanded = expand_source(&source, Kind::of(path))
        .map_err(|err| Error::new(render(path, &source, err)))?;
    if let Some(parent) = output.parent() {
        fs::create_dir_all(parent).map_err(|err| io_error(parent, &err))?;
    }
    // rustc reports errors in generated code at the output; the header leads back to the source.
    let text = format!(
        "// Generated by rustx-build from {}; edit that file instead.\n{expanded}",
        path.display()
    );
    fs::write(&output, text).map_err(|err| io_error(&output, &err))?;
    Ok(output)
}

fn expand_dir_into(dir: &Path, out_dir: &Path) -> Result<Vec<PathBuf>, Error> {
    rerun_if_changed(dir)?;
    let mut sources = Vec::new();
    find_rustx(dir, &mut sources)?;
    // A stable order keeps the error list the same from build to build.
    sources.sort();
    let mut outputs = Vec::new();
    let mut errors = Vec::new();
    for source in sources {
        match expand_into(&source, out_dir) {
            Ok(output) => outputs.push(output),
            Err(err) => errors.push(err.message),
        }
    }
    if errors.is_empty() {
        Ok(outputs)
    } else {
        Err(Error::new(errors.join("\n")))
    }
}

fn find_rustx(dir: &Path, found: &mut Vec<PathBuf>) -> Result<(), Error> {
    for entry in fs::read_dir(dir).map_err(|err| io_error(dir, &err))? {
        let entry = entry.map_err(|err| io_error(dir, &err))?;
        let file_type = entry
            .file_type()
            .map_err(|err| io_error(&entry.path(), &err))?;
        // `file_type` does not follow symlinks, so a link back up the tree cannot loop.
        if file_type.is_dir() {
            find_rustx(&entry.path(), found)?;
        } else if Kind::of(&entry.path()) == Kind::Sugar {
            found.push(entry.path());
        }
    }
    Ok(())
}

/// Checks `path` before it reaches a Cargo directive or a path below `OUT_DIR`, then prints the
/// directive.
fn rerun_if_changed(path: &Path) -> Result<(), Error> {
    // `..` or an absolute path would write outside `OUT_DIR`; a line break would end the
    // directive early and start another one.
    let inside = path
        .components()
        .all(|c| matches!(c, Component::Normal(_) | Component::CurDir))
        && path.components().any(|c| matches!(c, Component::Normal(_)));
    let printable = path.to_str().is_some_and(|s| !s.contains(['\n', '\r']));
    if !inside || !printable {
        return Err(Error::new(format!(
            "{}: give a UTF-8 path relative to the package root, without `..` or line breaks",
            path.display()
        )));
    }
    println!("cargo::rerun-if-changed={}", path.display());
    Ok(())
}

fn io_error(path: &Path, err: &std::io::Error) -> Error {
    Error::new(format!("{}: {err}", path.display()))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A fresh output directory per test; nextest runs each test in a process of its own.
    fn scratch(test: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("rustx-build-{}-{test}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        dir
    }

    #[test]
    fn the_output_mirrors_the_relative_path_with_an_rs_extension() {
        let out = scratch("mirror");
        let output = expand_into(Path::new("tests/fixtures/ok/counter.rustx"), &out).unwrap();
        assert_eq!(output, out.join("tests/fixtures/ok/counter.rs"));
        let text = fs::read_to_string(output).unwrap();
        assert!(
            text.starts_with(
                "// Generated by rustx-build from tests/fixtures/ok/counter.rustx; edit that file instead.\n"
            ),
            "{text}"
        );
        assert!(text.contains("let mut count = 0;"), "{text}");
    }

    #[test]
    fn a_sugar_error_names_the_rustx_file_and_line() {
        let err = expand_into(
            Path::new("tests/fixtures/bad/tilde.rustx"),
            &scratch("error"),
        )
        .unwrap_err();
        let expected = "tests/fixtures/bad/tilde.rustx:3:22: expected a trait after `~`, as in `~Trait` or `~Fn(T) -> U`";
        assert_eq!(err.to_string(), expected);
        assert_eq!(format!("{err:?}"), expected);
    }

    #[test]
    fn a_missing_file_is_reported_with_its_path() {
        let err =
            expand_into(Path::new("tests/fixtures/none.rustx"), &scratch("missing")).unwrap_err();
        assert!(
            err.to_string().starts_with("tests/fixtures/none.rustx: "),
            "{err}"
        );
    }

    #[test]
    fn a_path_that_leaves_out_dir_or_breaks_a_directive_is_rejected() {
        let out = scratch("reject");
        for path in [
            "../a.rustx",
            "/tmp/a.rustx",
            "src/../../a.rustx",
            "a\nb.rustx",
            "",
        ] {
            let err = expand_into(Path::new(path), &out).unwrap_err();
            assert!(
                err.to_string().contains("relative to the package root"),
                "{path:?}: {err}"
            );
        }
        assert!(!out.exists());
    }

    #[test]
    fn a_directory_expands_every_rustx_file_and_collects_the_errors() {
        let out = scratch("dir");
        let err = expand_dir_into(Path::new("tests/fixtures"), &out).unwrap_err();
        assert_eq!(
            err.to_string(),
            "tests/fixtures/bad/tilde.rustx:3:22: expected a trait after `~`, as in `~Trait` or `~Fn(T) -> U`"
        );
        assert!(out.join("tests/fixtures/ok/counter.rs").is_file());
        assert!(out.join("tests/fixtures/ok/nested/greet.rs").is_file());
        assert!(!out.join("tests/fixtures/ok/ignored.rs").exists());
    }

    #[test]
    fn a_directory_without_errors_returns_its_outputs_in_order() {
        let out = scratch("dir_ok");
        let outputs = expand_dir_into(Path::new("tests/fixtures/ok"), &out).unwrap();
        assert_eq!(
            outputs,
            [
                out.join("tests/fixtures/ok/counter.rs"),
                out.join("tests/fixtures/ok/nested/greet.rs")
            ]
        );
    }

    #[test]
    fn every_message_line_becomes_its_own_cargo_error() {
        let err = Error::new("a.rustx:1:1: first\na.rustx:2:1: second\ncargo::warning=x".into());
        let lines: Vec<String> = err.cargo_lines().collect();
        assert_eq!(
            lines,
            [
                "cargo::error=a.rustx:1:1: first",
                "cargo::error=a.rustx:2:1: second",
                "cargo::error=cargo::warning=x"
            ]
        );
    }
}
