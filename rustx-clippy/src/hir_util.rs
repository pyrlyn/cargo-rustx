//! Helpers of the late lints: telling the user's code from rustx's output, and building edits.

use clippy_utils::source::snippet_opt;
use rustc_errors::Applicability;
use rustc_hir::def::Res;
use rustc_hir::def_id::LocalDefId;
use rustc_hir::{self as hir, ExprKind};
use rustc_lint::{LateContext, LintContext};
use rustc_span::hygiene::{ExpnKind, MacroKind};
use rustc_span::{ExpnId, Span};

use crate::util;

/// Whether `rustx` is a direct dependency of the crate being linted. Only then does a suggested
/// `#[rustx::..]` attribute resolve; rustc loads a dependency's metadata only once the crate
/// uses it, so an unused `rustx` entry in `Cargo.toml` reads as absent too.
pub fn uses_rustx(cx: &LateContext<'_>) -> bool {
    cx.tcx.crates(()).iter().any(|&krate| {
        cx.tcx.crate_name(krate).as_str() == "rustx"
            && cx.tcx.extern_crate(krate).is_some_and(|extern_crate| extern_crate.is_direct())
    })
}

/// `exact` downgraded when the crate does not depend on `rustx`.
pub fn applicability(cx: &LateContext<'_>, exact: bool) -> Applicability {
    if exact && uses_rustx(cx) {
        Applicability::MachineApplicable
    } else {
        Applicability::MaybeIncorrect
    }
}

/// The note added when the suggestion needs a dependency the crate does not have.
pub fn note_dependency(cx: &LateContext<'_>, diag: &mut rustc_errors::Diag<'_, ()>) {
    if !uses_rustx(cx) {
        diag.note("the suggestion needs `rustx` as a dependency of this crate");
    }
}

/// Whether the item `def_id` spanning `span`, whose text starts with `keyword` after an optional
/// visibility, was written by the user rather than generated.
///
/// An item a macro wrote has a span from that expansion, except inside the output of an
/// attribute macro: rustx re-emits the user's items with their own spans and gives generated
/// ones spans of the sugar tokens they replace (a field name, say). Such an item is the user's
/// only if its text is an item of that kind.
pub fn is_hand_written(cx: &LateContext<'_>, def_id: LocalDefId, span: Span, keyword: &str) -> bool {
    if span.from_expansion() {
        return false;
    }
    let expn = cx.tcx.expn_that_defined(def_id.to_def_id());
    if expn == ExpnId::root() {
        return true;
    }
    matches!(expn.expn_data().kind, ExpnKind::Macro(MacroKind::Attr, _))
        && snippet_opt(cx, span).is_some_and(|text| starts_with_keyword(&text, keyword))
}

fn starts_with_keyword(text: &str, keyword: &str) -> bool {
    let mut rest = text.trim_start();
    if let Some(after) = rest.strip_prefix("pub") {
        rest = after.trim_start();
        if rest.starts_with('(')
            && let Some(close) = rest.find(')')
        {
            rest = rest[close + 1..].trim_start();
        }
    }
    let rest = rest.strip_prefix("unsafe ").map_or(rest, str::trim_start);
    rest.strip_prefix(keyword)
        .is_some_and(|after| after.starts_with(|c: char| c.is_whitespace() || c == '<'))
}

/// Whether an impl of a trait on the local type `adt` was generated by a rustx macro, which
/// tells that the type already sits under `#[rustx::display]` or `#[rustx::sugared]`.
pub fn has_rustx_impl(cx: &LateContext<'_>, adt: LocalDefId) -> bool {
    cx.tcx.hir_crate_items(()).definitions().any(|def_id| {
        matches!(cx.tcx.def_kind(def_id), rustc_hir::def::DefKind::Impl { of_trait: true })
            && cx
                .tcx
                .type_of(def_id)
                .instantiate_identity()
                .skip_norm_wip()
                .ty_adt_def()
                .is_some_and(|def| def.did() == adt.to_def_id())
            && from_rustx(cx, cx.tcx.expn_that_defined(def_id.to_def_id()))
    })
}

/// Whether `expn` is the expansion of a macro of the `rustx_macros` crate.
pub fn from_rustx(cx: &LateContext<'_>, expn: ExpnId) -> bool {
    expn.expn_data()
        .macro_def_id
        .is_some_and(|id| cx.tcx.crate_name(id.krate).as_str() == "rustx_macros")
}

/// The edit inserting the attribute `attr` on its own line before the item spanning `item`.
pub fn insert_attr(cx: &LateContext<'_>, item: Span, attr: &str) -> (Span, String) {
    let indent = util::indent(cx.sess().source_map(), item);
    (item.shrink_to_lo(), format!("{attr}\n{indent}"))
}

/// The edit removing the item spanning `span`, with the lines it fills.
pub fn remove(cx: &LateContext<'_>, span: Span) -> (Span, String) {
    (util::whole_lines(cx.sess().source_map(), span), String::new())
}

/// The edit removing the item `hir_id` spanning `span` together with its outer attributes and
/// doc comments, with the lines they fill.
pub fn remove_with_attrs(cx: &LateContext<'_>, hir_id: hir::HirId, span: Span) -> (Span, String) {
    let lo = cx
        .tcx
        .hir_attrs(hir_id)
        .iter()
        .map(|attr| attr.span())
        .filter(|attr| !attr.from_expansion() && attr.lo() < span.lo())
        .map(Span::lo)
        .min()
        .unwrap_or(span.lo());
    remove(cx, span.with_lo(lo))
}

/// `expr` without the blocks around it that hold nothing else: `{ { e } }` is `e`.
pub fn peel_blocks<'a>(mut expr: &'a hir::Expr<'a>) -> &'a hir::Expr<'a> {
    while let ExprKind::Block(block, None) = expr.kind
        && block.stmts.is_empty()
        && let Some(inner) = block.expr
    {
        expr = inner;
    }
    expr
}

/// The single local `expr` names, if it is a path to one.
pub fn local(expr: &hir::Expr<'_>) -> Option<hir::HirId> {
    match expr.kind {
        ExprKind::Path(hir::QPath::Resolved(None, path)) => match path.res {
            Res::Local(id) => Some(id),
            _ => None,
        },
        _ => None,
    }
}
